"""Request dependencies: services, DB session, device id, app version gate, integrity."""

from __future__ import annotations

import re
from collections.abc import AsyncIterator

from fastapi import Depends, Header, Request
from sqlalchemy.ext.asyncio import AsyncSession

from .errors import ApiError
from .services.container import Services

_DEVICE_ID = re.compile(r"^[A-Za-z0-9_-]{8,64}$")


def get_services(request: Request) -> Services:
    return request.app.state.services


async def get_session(services: Services = Depends(get_services)) -> AsyncIterator[AsyncSession]:
    async with services.db.sessionmaker() as session:
        yield session


def device_id(x_device_id: str | None = Header(default=None)) -> str:
    """Anonymous random id generated by the app (not the Android ID)."""
    if not x_device_id or not _DEVICE_ID.match(x_device_id):
        raise ApiError(400, "missing_device_id", "Thiếu hoặc sai mã thiết bị (X-Device-Id).")
    return x_device_id


def _version_tuple(v: str) -> tuple[int, ...]:
    return tuple(int(p) for p in re.findall(r"\d+", v)[:3]) or (0,)


def check_app_version(
    x_app_version: str | None = Header(default=None),
    services: Services = Depends(get_services),
) -> None:
    if x_app_version and _version_tuple(x_app_version) < _version_tuple(services.settings.min_app_version):
        raise ApiError(426, "upgrade_required", "Phiên bản app đã cũ, vui lòng cập nhật để tiếp tục.")


async def require_integrity(services: Services, token: str | None, expected_hash: str) -> None:
    verdict = await services.integrity.verify(token, expected_hash)
    if not verdict.ok:
        raise ApiError(403, "integrity_failed", "Không xác minh được ứng dụng. Hãy cài app từ Google Play.",
                       detail=verdict.reason)
